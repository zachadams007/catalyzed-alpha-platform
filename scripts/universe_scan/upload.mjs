/**
 * Publish a freshly-computed scan to the shared `daily_signals` cache using the
 * Supabase SERVICE-ROLE key (server-side only - bypasses RLS).
 *
 * The client read path (`src/data/dailySignalsCache.ts`) is the durable
 * interface: it reads `{ signals, run, computed_at, meta }` for today's US/Eastern
 * `market_day`. Writing here from a scheduled job means every tester reads the
 * broad universe with ZERO vendor calls and no per-device scan.
 *
 * We UPSERT (on conflict `market_day`) so a re-run or a late run cleanly replaces
 * the day's row - the service role is authoritative. The upsert is retried a few
 * times: a large body over a flaky connection occasionally throws a low-level
 * `fetch failed`, and the day's compute is far too expensive to lose to one blip.
 */

import { createClient } from "@supabase/supabase-js";

/** Canonical shared market-day key: the US/Eastern calendar date (YYYY-MM-DD). */
export function marketDayKey(now = new Date()) {
  return new Intl.DateTimeFormat("en-CA", {
    timeZone: "America/New_York",
    year: "numeric",
    month: "2-digit",
    day: "2-digit",
  }).format(now);
}

const sleep = (ms) => new Promise((r) => setTimeout(r, ms));

export async function uploadDailySignals(signals, run, meta = {}) {
  const url = process.env.SUPABASE_URL || process.env.VITE_SUPABASE_URL;
  const serviceKey = process.env.SUPABASE_SERVICE_ROLE_KEY;
  if (!url) throw new Error("SUPABASE_URL (or VITE_SUPABASE_URL) is required to publish.");
  if (!serviceKey) throw new Error("SUPABASE_SERVICE_ROLE_KEY is required to publish.");
  if (!Array.isArray(signals) || signals.length === 0) {
    throw new Error("Refusing to publish an empty signal set.");
  }

  const supabase = createClient(url, serviceKey, {
    auth: { persistSession: false, autoRefreshToken: false },
  });

  const day = marketDayKey();
  const computedAt = run?.finishedAt ?? new Date().toISOString();

  // Strip synthetic/bulky fields that push the JSON blob past Supabase's free-tier
  // statement timeout (~2-3 s). priceSeries (252 PricePoints × 500 signals ≈ 5 MB)
  // is generated by genPriceSeries() and is not real historical data; the client
  // uses priceHistory (30 closes) for sparklines and live Alpaca for charts.
  // socialPosts are sample-only in the cloud scan - also safe to drop.
  const stripped = signals.map(({ priceSeries: _ps, socialPosts: _sp, ...rest }) => rest);

  const row = {
    market_day: day,
    signals: stripped,
    run: run ?? null,
    signal_count: signals.length,
    computed_at: computedAt,
    meta: {
      provider: run?.provider ?? "Scheduled broad-universe scan",
      universeSize: run?.universeSize ?? signals.length,
      ...meta,
    },
  };

  let lastErr;
  for (let attempt = 1; attempt <= 4; attempt++) {
    try {
      const { error } = await supabase
        .from("daily_signals")
        .upsert(row, { onConflict: "market_day" });
      if (!error) return { day, count: signals.length, computedAt };
      lastErr = new Error(`${error.message} (${error.code ?? "?"})`);
    } catch (err) {
      lastErr = err; // low-level transport error (e.g. "fetch failed")
    }
    if (attempt < 4) await sleep(attempt * 1500);
  }
  throw new Error(`daily_signals upsert failed after retries: ${lastErr?.message ?? lastErr}`);
}
